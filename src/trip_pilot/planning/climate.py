def _degrees(value: int) -> str:
    return f"+{value} °C" if value > 0 else f"−{-value} °C" if value < 0 else "0 °C"


def climate_text(slug: str, month: int) -> str | None:
    """«днём около +30 °C, море +27 °C»; направления нет в таблице — None."""
    months = CLIMATE.get(slug)
    if months is None:
        return None
    air, sea = months[month - 1]
    text = f"днём около {_degrees(air)}"
    return f"{text}, море {_degrees(sea)}" if sea is not None else text
